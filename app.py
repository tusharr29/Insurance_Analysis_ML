# Load model and scaler
BASE_DIR = Path(__file__).parent

@st.cache_resource
def load_artifacts():
    model = joblib.load(BASE_DIR / "insurance_model.pkl")
    scaler = joblib.load(BASE_DIR / "scaler.pkl")
    return model, scaler

try:
    model, scaler = load_artifacts()
except FileNotFoundError:
    st.error("Model or scaler not found. Please run main.py first.")
    st.stop()

# Application heading
st.title("🏥 Insurance Cost Prediction System")
st.write(
    "Predict medical insurance charges using Machine Learning."
)

st.divider()

st.subheader("Enter Customer Details")

col1, col2 = st.columns(2)

with col1:
    age = st.number_input("Age", 18, 100, 30)

    sex = st.selectbox(
        "Gender",
        ["male", "female"]
    )

    bmi = st.number_input(
        "BMI",
        min_value=10.0,
        max_value=60.0,
        value=25.0,
        step=0.1
    )

with col2:
    children = st.number_input(
        "Number of Children",
        min_value=0,
        max_value=10,
        value=0
    )

    smoker = st.selectbox(
        "Smoker",
        ["yes", "no"]
    )

st.divider()

if st.button("Predict Insurance Charges", type="primary"):

    # Prepare input
    input_data = pd.DataFrame({
        'age': [age],
        'is_female': [1 if sex == 'female' else 0],
        'bmi': [bmi],
        'children': [children],
        'is_smoker': [1 if smoker == 'yes' else 0]
    })

    # Apply same scaling used during training
    numeric_features = ['age', 'bmi', 'children']

    input_data[numeric_features] = scaler.transform(
        input_data[numeric_features]
    )

    # Prediction
    prediction = model.predict(input_data)[0]

    st.success("Prediction Generated Successfully!")

    st.metric(
        label="Estimated Insurance Charges",
        value=f"${prediction:,.2f}"
    )

    st.info(
        "This is an estimated prediction generated by a "
        "Machine Learning model, not an actual insurance quote."
    )

st.divider()

